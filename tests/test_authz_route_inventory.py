def test_unmapped_routes_are_explicit_and_new_writes_fail() -> None:
    from app.main import app

    coverage = audit_route_coverage(app)
    writes = frozenset(item for item in coverage.unmapped if item[0] in _WRITE_METHODS)
    others = frozenset(item for item in coverage.unmapped if item[0] not in _WRITE_METHODS)
    assert writes == _ACCOUNTED_UNMAPPED_WRITES
    assert others == _ACCOUNTED_UNMAPPED_OTHER
    excluded_paths = {path for _method, path in coverage.intentionally_excluded}
    for prefix in _UNMAPPED_BUSINESS_PREFIXES:
        assert not any(path == prefix or path.startswith(prefix + "/") for path in excluded_paths)
        assert any(path == prefix or path.startswith(prefix + "/") for _method, path in coverage.unmapped)
